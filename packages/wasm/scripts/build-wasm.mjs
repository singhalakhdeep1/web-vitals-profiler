// Compiles src/vitals.wat and embeds the bytes in src/vitals-wasm.generated.ts (so every runtime can load the module
// synchronously without fetching a file). Run after changing the .wat: pnpm --filter @wvp/wasm build:wasm
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import initWabt from "wabt";

const here = dirname(fileURLToPath(import.meta.url));
const watPath = resolve(here, "../src/vitals.wat");
const wabt = await initWabt();
const mod = wabt.parseWat("vitals.wat", readFileSync(watPath, "utf8"));
mod.validate();
const { buffer } = mod.toBinary({ log: false });
mod.destroy();
const b64 = Buffer.from(buffer).toString("base64");
writeFileSync(
  resolve(here, "../src/vitals-wasm.generated.ts"),
  `// Generated by scripts/build-wasm.mjs from vitals.wat (${buffer.length} bytes). Do not edit.\nexport const VITALS_WASM_BASE64 = "${b64}";\n`,
);
console.log(`vitals.wasm: ${buffer.length} bytes`);
